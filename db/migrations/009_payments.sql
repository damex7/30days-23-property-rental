-- 009: PAYMENTS, WEBHOOKS, REFUNDS and the EMAIL LOG (Day 22's design,
-- pointed at stays instead of ticket orders).

-- One row per Paystack transaction we start. A stay has one, normally; a
-- retry after a failed initialise could add another, so it isn't UNIQUE on
-- stay_id. What IS unique is success: see the partial index below.
CREATE TABLE payments (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- RESTRICT: money records outlive everything. A stay with a payment can't
  -- be deleted by accident (the demo cleanup deletes payments explicitly).
  stay_id     uuid        NOT NULL REFERENCES stays (id) ON DELETE RESTRICT,
  provider    text        NOT NULL DEFAULT 'paystack' CHECK (provider IN ('paystack', 'demo')),
  -- Generated by us, sent to Paystack, and the key every callback and
  -- webhook is matched on. UNIQUE: one reference, one payment.
  reference   text        NOT NULL UNIQUE CHECK (reference ~ '^(SB|DEMO)-[A-Z0-9-]{6,40}$'),
  -- What we ASKED for. A payment whose amount differs is refused (and
  -- flagged), however Paystack labels it.
  amount_kobo bigint      NOT NULL CHECK (amount_kobo > 0),
  currency    text        NOT NULL DEFAULT 'NGN' CHECK (currency = 'NGN'),
  status      text        NOT NULL DEFAULT 'initialized'
              CHECK (status IN ('initialized', 'success', 'failed', 'abandoned')),
  -- Kept so a replayed Reserve (same idempotency key) sends the guest to the
  -- SAME checkout page instead of starting a second transaction.
  authorization_url text  NULL,
  provider_transaction_id text NULL,
  channel     text        NULL,
  gateway_response text   NULL CHECK (gateway_response IS NULL OR length(gateway_response) <= 500),
  -- Set when a successful payment couldn't be honoured (wrong amount; the
  -- hold expired and the nights were taken). The refunds row says why.
  flagged     boolean     NOT NULL DEFAULT false,
  paid_at     timestamptz NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT payments_paid_at CHECK (status <> 'success' OR paid_at IS NOT NULL)
);
CREATE TRIGGER payments_set_updated_at BEFORE UPDATE ON payments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
-- EXACTLY ONCE, in the database: at most ONE successful payment per stay.
-- Even if two confirmations slipped past every lock, the second 'success'
-- update would be refused (23505).
CREATE UNIQUE INDEX payments_one_success_per_stay ON payments (stay_id) WHERE status = 'success';
CREATE INDEX payments_stay_idx ON payments (stay_id);

-- Every webhook delivery we accept, deduplicated. Paystack retries until it
-- gets a 200, so the same event can arrive several times; the UNIQUE key
-- makes the second insert a no-op, so it's processed once.
CREATE TABLE webhook_events (
  id           bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  provider     text        NOT NULL CHECK (provider = 'paystack'),
  -- sha256 of provider + event + reference + transaction id.
  dedupe_key   text        NOT NULL CHECK (dedupe_key ~ '^[0-9a-f]{64}$'),
  event_type   text        NOT NULL CHECK (length(event_type) <= 60),
  reference    text        NULL CHECK (reference IS NULL OR length(reference) <= 100),
  payload      jsonb       NOT NULL,
  received_at  timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz NULL,
  -- The confirm result when it wasn't a plain success ("mismatch", ...).
  error        text        NULL CHECK (error IS NULL OR length(error) <= 200),
  CONSTRAINT webhook_events_dedupe_key UNIQUE (provider, dedupe_key)
);
CREATE INDEX webhook_events_received_idx ON webhook_events (received_at DESC);

-- REFUNDS, recorded as PENDING and never sent (sending real refunds is out
-- of scope). A person (or Day 25's payouts) acts on the pending ones.
CREATE TABLE refunds (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- RESTRICT on both: a refund is a money record.
  stay_id     uuid        NOT NULL REFERENCES stays (id) ON DELETE RESTRICT,
  payment_id  uuid        NOT NULL REFERENCES payments (id) ON DELETE RESTRICT,
  amount_kobo bigint      NOT NULL CHECK (amount_kobo > 0),
  status      text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processed', 'failed')),
  -- 'cancellation' (by policy), 'unhonoured_payment' (paid but couldn't be
  -- confirmed: wrong amount, or the nights were gone).
  kind        text        NOT NULL CHECK (kind IN ('cancellation', 'unhonoured_payment')),
  reason      text        NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 300),
  -- The breakdown shown to the guest at cancellation.
  breakdown   jsonb       NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER refunds_set_updated_at BEFORE UPDATE ON refunds
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE INDEX refunds_stay_idx ON refunds (stay_id);
CREATE INDEX refunds_pending_idx ON refunds (created_at) WHERE status = 'pending';
-- One cancellation refund per stay, whatever a double click does.
CREATE UNIQUE INDEX refunds_one_cancellation ON refunds (stay_id) WHERE kind = 'cancellation';

-- SEND EACH EMAIL ONCE (Day 22): "claim" a row before sending. The UNIQUE
-- pair means a retried callback, a webhook racing the callback, or a cron
-- run twice can't send the same confirmation twice. If the send fails, the
-- claim is deleted so a later attempt can try again.
CREATE TABLE email_log (
  id         bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kind       text        NOT NULL CHECK (kind IN (
               'booking_confirmed_guest', 'booking_confirmed_host',
               'booking_cancelled_guest', 'booking_cancelled_host',
               'review_reminder', 'listing_rejected', 'listing_approved',
               'payment_unhonoured')),
  -- What the email is about: a stay id, or "<listing id>:<version>" for a
  -- listing decision (a listing can be rejected, edited and rejected again,
  -- and each decision deserves its own email). Not a foreign key: it points
  -- at one of two tables, and the log must survive demo cleanup.
  subject_id text        NOT NULL CHECK (length(subject_id) BETWEEN 1 AND 80),
  sent_to    citext      NOT NULL,
  sent_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT email_log_once UNIQUE (kind, subject_id)
);
